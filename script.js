function setLanguage(lang) {
  const safeLang = translations[lang] ? lang : "es";
  const dict = translations[safeLang];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (dict[key]) {
      element.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      element.setAttribute("placeholder", dict[key]);
    }
  });

  localStorage.setItem("language", safeLang);
  document.documentElement.lang = safeLang;
}

function updateLanguageButtons(activeLang) {
  document.querySelectorAll(".lang-btn").forEach((button) => {
    const isActive = button.getAttribute("data-lang") === activeLang;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const y = document.getElementById("y");
  if (y) y.textContent = new Date().getFullYear();

  const savedLanguage = localStorage.getItem("language") || "es";
  const langButtons = document.querySelectorAll(".lang-btn");

  setLanguage(savedLanguage);
  updateLanguageButtons(savedLanguage);

  langButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const lang = button.getAttribute("data-lang");
      setLanguage(lang);
      updateLanguageButtons(lang);
    });
  });

  const io = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        io.unobserve(entry.target);
      }
    }
  }, { threshold: 0.1 });

  document.querySelectorAll("[data-reveal]").forEach((el) => io.observe(el));
});
